namespace Ota.CoreEngine.Tests.Integration;

/// <summary>A controller that "forgot" to declare access. Only registered in the derived test host of AuthorizationAuditTests
/// (top-level: MVC does not discover nested controllers).</summary>
[ApiController, Route("test-undeclared")]
public sealed class UndeclaredController : ControllerBase
{
    [HttpGet] public IActionResult Get() => Ok("wide open");
}

/// <summary>P3-5: nothing is reachable by accident. Every endpoint the app exposes must DECLARE who may call it; the anonymous ones are an exact,
/// reviewed list (adding one is a conscious edit here); and every protected endpoint is probed with the wrong kinds of caller. An endpoint that
/// declares nothing is refused by default, and this test also fails the build so the omission is fixed, not merely contained.</summary>
[Collection(OtaCoreEngineCollection.Name)]
public class AuthorizationAuditTests(OtaCoreEngineFixture fixture)
{
    private sealed record Ep(string Methods, string Pattern, bool Anonymous, IReadOnlyList<IAuthorizeData> Auth, bool IsGrpc)
    {
        public override string ToString() => $"{Methods} {Pattern}";
    }

    private List<Ep> Endpoints() => fixture.Factory.Services.GetRequiredService<EndpointDataSource>().Endpoints.OfType<RouteEndpoint>()
        .Select(e => new Ep(
            string.Join(",", e.Metadata.GetMetadata<HttpMethodMetadata>()?.HttpMethods ?? ["*"]),
            e.RoutePattern.RawText ?? "",
            e.Metadata.GetMetadata<IAllowAnonymous>() is not null,
            e.Metadata.GetOrderedMetadata<IAuthorizeData>().ToList(),
            (e.RoutePattern.RawText ?? "").Contains("ota.v1.") || (e.RoutePattern.RawText ?? "").Contains("unimplemented")))
        .OrderBy(e => e.Pattern).ThenBy(e => e.Methods).ToList();

    // ------------------------------------------------------------------------------------------ declarations

    [Fact]
    public void EveryEndpoint_DeclaresWhoMayCallIt()
    {
        // (the gRPC "unimplemented" catch-alls are generated by the framework and answer UNIMPLEMENTED; the real RPCs are checked below)
        var undeclared = Endpoints().Where(e => !e.Anonymous && e.Auth.Count == 0 && !e.Pattern.Contains("unimplemented")).Select(e => e.ToString()).ToList();

        Assert.True(undeclared.Count == 0, "Endpoints with no [Authorize] and no [AllowAnonymous]: " + string.Join("; ", undeclared));
    }

    [Fact]
    public void NoEndpoint_IsProtectedByABareAuthorize_EachNamesAPolicyOrRole()
    {
        var bare = Endpoints().Where(e => !e.Anonymous && e.Auth.Count > 0 && e.Auth.All(a => string.IsNullOrEmpty(a.Policy) && string.IsNullOrEmpty(a.Roles)))
            .Select(e => e.ToString()).ToList();

        Assert.True(bare.Count == 0, "Bare [Authorize] (any signed-in caller of the default kind): " + string.Join("; ", bare));
    }

    /// <summary>The COMPLETE list of endpoints anyone on the internet may call. If you add an anonymous endpoint, add it here on purpose — and
    /// think about what a stranger can do with it (rate limits, what it reveals, what it creates).</summary>
    private static readonly string[] KnownAnonymous =
    [
        "GET /", "GET /.well-known/jwks.json", "* /healthz",
        "GET api/v1/airlines", "GET api/v1/airports", "GET api/v1/tenant-registry/resolve",
        // agent authentication (they cannot require a token: they issue one)
        "POST api/v1/auth/register", "POST api/v1/auth/login", "POST api/v1/auth/verify-device", "POST api/v1/auth/refresh",
        "POST api/v1/auth/forgot-password", "POST api/v1/auth/reset-password",
        // frontends exchanging client credentials for a service token
        "POST api/v1/auth/service/token",
        // consumer sign-in (they issue the customer's token)
        "POST api/v1/auth/customer/social", "POST api/v1/auth/customer/refresh", "POST api/v1/auth/customer/logout",
        "POST api/v1/auth/customer/register", "POST api/v1/auth/customer/login", "POST api/v1/auth/customer/verify-email",
        "POST api/v1/auth/customer/forgot-password", "POST api/v1/auth/customer/reset-password",
        // guests reach one booking by proof (claim token, or reference + surname) — see GuestBookingsController
        "POST api/v1/guest/bookings", "POST api/v1/guest/bookings/lookup", "POST api/v1/guest/bookings/access", "POST api/v1/guest/bookings/send-link",
        "POST api/v1/guest/bookings/cancel",
        // SSLCommerz server-to-server IPN (no customer session; validated against the gateway)
        "POST api/v1/payments/sslcommerz/ipn",
    ];

    [Fact]
    public void TheAnonymousEndpoints_AreExactlyTheReviewedList()
    {
        var actual = Endpoints().Where(e => e.Anonymous && !e.IsGrpc).Select(e => e.ToString()).Order().ToList();

        Assert.Equal(KnownAnonymous.Order(), actual);
    }

    [Fact]
    public void EveryRpc_RequiresAnAuthenticationSchemeAndAPolicy()
    {
        var rpcs = Endpoints().Where(e => e.Pattern.StartsWith("/ota.v1.") ).ToList();

        Assert.NotEmpty(rpcs);
        foreach (var rpc in rpcs)
        {
            Assert.False(rpc.Anonymous, $"{rpc} is anonymous");
            Assert.All(rpc.Auth, a => { Assert.False(string.IsNullOrEmpty(a.Policy), $"{rpc} has no policy"); Assert.Equal(GrpcAuth.Scheme, a.AuthenticationSchemes); });
        }
    }

    [Fact]
    public async Task ByDefault_AnUndeclaredEndpointIsRefused()
    {
        var policy = await fixture.Factory.Services.GetRequiredService<IAuthorizationPolicyProvider>().GetFallbackPolicyAsync();

        Assert.NotNull(policy);
        Assert.Contains(policy!.Requirements, r => r is Microsoft.AspNetCore.Authorization.Infrastructure.DenyAnonymousAuthorizationRequirement);
    }

    // ------------------------------------------------------------------------------------------ probing every protected endpoint

    private static string Fill(string pattern) => "/" + Regex.Replace(pattern.TrimStart('/'), @"\{(\w+)(:guid)?\}", m => m.Groups[2].Success ? Guid.NewGuid().ToString() : "x");

    private static HttpRequestMessage Request(Ep e, string? bearer)
    {
        var method = e.Methods.Split(',')[0];
        var request = new HttpRequestMessage(new HttpMethod(method == "*" ? "GET" : method), Fill(e.Pattern));
        if (method is "POST" or "PUT") request.Content = JsonContent.Create(new { });
        if (bearer is not null) request.Headers.Authorization = new("Bearer", bearer);
        request.Headers.Add("X-Tenant-ID", "audit-tenant");
        return request;
    }

    private List<Ep> Protected(Func<Ep, bool> pick) => Endpoints().Where(e => !e.Anonymous && !e.IsGrpc && e.Auth.Count > 0 && pick(e)).ToList();
    private static bool IsCustomerEndpoint(Ep e) => e.Auth.Any(a => a.AuthenticationSchemes == CustomerAuth.CustomerBearer.Scheme);

    private async Task<string> ServiceTokenAsync()
    {
        var r = await fixture.Factory.CreateClient().PostAsJsonAsync("/api/v1/auth/service/token", new { clientId = TestServiceClients.BroadId, clientSecret = TestServiceClients.BroadSecret });
        return (await r.Content.ReadFromJsonAsync<JsonElement>()).GetProperty("accessToken").GetString()!;
    }

    private static string CustomerToken() => new JwtSecurityTokenHandler().WriteToken(new JwtSecurityToken("ota-core-engine", TokenAudiences.Customers, new[]
    {
        new Claim("sub", Guid.NewGuid().ToString()), new Claim("tenant_id", "audit-tenant"), new Claim("channel", "B2C"),
        new Claim(ActorTypes.ClaimName, "customer"), new Claim("token_type", "access"), new Claim("sid", "s"), new Claim("iat_ms", "1"),
    }, expires: DateTime.UtcNow.AddMinutes(5), signingCredentials: TestJwtKeys.CustomersSigning()));

    [Fact]
    public async Task EveryProtectedEndpoint_RefusesACallerWithNoToken()
    {
        var client = fixture.Factory.CreateClient();
        var eps = Protected(_ => true);
        Assert.NotEmpty(eps);

        foreach (var e in eps)
            Assert.True((await client.SendAsync(Request(e, null))).StatusCode == HttpStatusCode.Unauthorized, $"{e} answered a caller with no token");
    }

    [Fact]
    public async Task EveryAgentEndpoint_RefusesACustomerToken_AndAServiceToken()
    {
        var client = fixture.Factory.CreateClient();
        var (customer, service) = (CustomerToken(), await ServiceTokenAsync());
        var eps = Protected(e => !IsCustomerEndpoint(e));
        Assert.NotEmpty(eps);

        foreach (var e in eps)
        {
            Assert.True((await client.SendAsync(Request(e, customer))).StatusCode == HttpStatusCode.Unauthorized, $"{e} accepted a CUSTOMER token");
            Assert.True((await client.SendAsync(Request(e, service))).StatusCode == HttpStatusCode.Unauthorized, $"{e} accepted a SERVICE token");
        }
    }

    [Fact]
    public async Task EveryCustomerEndpoint_RefusesAnAgentToken_AndAServiceToken()
    {
        var client = fixture.Factory.CreateClient();
        var (_, _, agent) = await TestData.SeedAgentAsync(fixture.Factory);
        var service = await ServiceTokenAsync();
        var eps = Protected(IsCustomerEndpoint);
        Assert.NotEmpty(eps);

        foreach (var e in eps)
        {
            Assert.True((await client.SendAsync(Request(e, agent))).StatusCode == HttpStatusCode.Unauthorized, $"{e} accepted an AGENT token");
            Assert.True((await client.SendAsync(Request(e, service))).StatusCode == HttpStatusCode.Unauthorized, $"{e} accepted a SERVICE token");
        }
    }

    [Fact]
    public async Task EveryPlatformAdminEndpoint_RefusesAnOrdinaryAgentUser_With403()
    {
        var (tenant, _, _) = await TestData.SeedAgentAsync(fixture.Factory);
        var (_, staffToken) = await TestData.SeedAgentUserAsync(fixture.Factory, tenant, UserRole.AgencyUser);
        var (_, adminOfAgencyToken) = await TestData.SeedAgentUserAsync(fixture.Factory, tenant, UserRole.AgencyAdmin);
        var client = fixture.Factory.CreateClient();
        var eps = Protected(e => e.Auth.Any(a => a.Policy == RestPolicies.PlatformAdmin));
        Assert.NotEmpty(eps);

        foreach (var e in eps)
        {
            Assert.True((await client.SendAsync(Request(e, staffToken))).StatusCode == HttpStatusCode.Forbidden, $"{e} let agency STAFF in");
            Assert.True((await client.SendAsync(Request(e, adminOfAgencyToken))).StatusCode == HttpStatusCode.Forbidden, $"{e} let an AGENCY admin in (only a platform admin may)");
        }
    }

    [Fact]
    public void PlatformAdminOnlyAreas_StayPlatformAdminOnly()
    {
        // Pinned so that quietly loosening one of these to a weaker policy is a failing test, not a silent change
        // (the probe below only looks at endpoints that still DECLARE the policy).
        foreach (var prefix in new[] { "api/v1/agencies", "api/v1/agent-tiers", "api/v1/markup-rules", "api/v1/exchange-rates", "api/v1/admin/cancellation-requests" })
        {
            var eps = Endpoints().Where(e => e.Pattern.StartsWith(prefix, StringComparison.OrdinalIgnoreCase)).ToList();
            Assert.NotEmpty(eps);
            Assert.All(eps, e => Assert.True(e.Auth.Any(a => a.Policy == RestPolicies.PlatformAdmin), $"{e} is not PlatformAdmin"));
        }
    }

    [Fact]
    public async Task ARealPlatformAdmin_IsNotBlockedByThePolicy()
    {
        var (tenant, _, _) = await TestData.SeedAgentAsync(fixture.Factory);
        var admin = await TestData.SeedAdminUserAsync(fixture.Factory, tenant);
        var client = fixture.Factory.CreateAuthenticatedClient(admin);

        var response = await client.GetAsync("/api/v1/agencies");

        Assert.Equal(HttpStatusCode.OK, response.StatusCode); // the probe above would pass vacuously if the policy refused everyone
    }

    // ------------------------------------------------------------------------------------------ default deny, demonstrated

    [Fact]
    public async Task AControllerThatForgetsToDeclareAccess_IsNotServedToTheWorld()
    {
        var host = fixture.Factory.WithWebHostBuilder(b => b.ConfigureServices(s => s.AddControllers().AddApplicationPart(typeof(UndeclaredController).Assembly)));
        var (_, _, agent) = await TestData.SeedAgentAsync(fixture.Factory);

        Assert.Equal(HttpStatusCode.Unauthorized, (await host.CreateClient().GetAsync("/test-undeclared")).StatusCode);   // the world: refused
        Assert.Equal(HttpStatusCode.Unauthorized, (await ClientWith(host, CustomerToken()).GetAsync("/test-undeclared")).StatusCode);
        Assert.Equal(HttpStatusCode.OK, (await ClientWith(host, agent).GetAsync("/test-undeclared")).StatusCode);          // …a signed-in agent is the floor
    }

    private static HttpClient ClientWith(Microsoft.AspNetCore.Mvc.Testing.WebApplicationFactory<Program> f, string bearer)
    {
        var c = f.CreateClient();
        c.DefaultRequestHeaders.Authorization = new("Bearer", bearer);
        return c;
    }
}
